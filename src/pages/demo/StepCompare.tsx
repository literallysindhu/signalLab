import { BarChart3, Download, FileJson, FileText, Loader2, Play, RotateCcw, X } from 'lucide-react';
import { useState } from 'react';
import { compareOutcomes, simulateLink, type ExperimentConfig, type ExperimentPoint, type Modulation } from '../../engine';
import { SweepChart } from '../../components/SweepChart';
import { Banner, EmptyState, PrimaryButton, ProgressBar, SecondaryButton, StatusBadge } from '../../components/ui';
import { downloadFile, pointsToCsv } from '../../lib/export';
import { fmtBer, fmtDb, fmtMs, fmtPct } from '../../lib/format';
import { useExperimentRunner } from '../../lib/useExperimentRunner';
import { modsFor, useDemo, type DemoComparison } from './DemoContext';
import { StepFrame } from './StepFrame';
import type { StepProps } from './StepSensor';
import { statusOf } from './StepReceive';

const CURRENT_PACKETS = 200;
const SWEEP_PACKETS = 60;
const SNR_SWEEP = [-5, 0, 5, 10, 15, 20, 25, 30];
const DIST_SWEEP = [1, 2, 3, 5, 7, 10, 15, 20, 30];

export function StepCompare({ hint }: StepProps) {
  const { validTransmission, setTransmission, selection, params, reading, inputKey, comparison, setComparison, restart, presentation } = useDemo();
  const runner = useExperimentRunner();
  const [stage, setStage] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const mods = modsFor(selection);
  const other: Modulation | null = mods.length === 1 ? (mods[0] === 'ASK' ? 'FSK' : 'ASK') : null;
  const results = validTransmission?.results;
  const cmp = comparison && comparison.key === inputKey ? comparison : null;

  function runOther() {
    if (!other || !validTransmission) return;
    const r = simulateLink(reading, other, params, { keepSignals: true });
    setTransmission({ key: validTransmission.key, results: { ...validTransmission.results, [other]: r } });
  }

  async function runComparison() {
    setError(null);
    const base = { ...params };
    const mk = (name: string, snr: number[], dist: number[], packets: number): ExperimentConfig => ({
      name,
      modulations: ['ASK', 'FSK'],
      snrValues: snr,
      distanceValues: dist,
      paddingValues: [params.paddingBytes],
      packetsPerPoint: packets,
      repetitions: 1,
      base,
    });
    try {
      setStage('1 of 3 · Current settings');
      const a = await runner.run(mk(`Guided demo: current settings`, [params.snrDb], [params.distanceM], CURRENT_PACKETS));
      setStage('2 of 3 · BER vs SNR sweep');
      const b = await runner.run(mk(`Guided demo: SNR sweep at ${params.distanceM} m`, SNR_SWEEP, [params.distanceM], SWEEP_PACKETS));
      setStage('3 of 3 · PDR vs distance sweep');
      const c = await runner.run(mk(`Guided demo: distance sweep at ${params.snrDb} dB`, [params.snrDb], DIST_SWEEP, SWEEP_PACKETS));
      const get = (m: Modulation) => a.points.find((p) => p.modulation === m)!;
      const next: DemoComparison = { key: inputKey, current: { ASK: get('ASK'), FSK: get('FSK') }, snrSweep: b.points, distanceSweep: c.points, runs: [a, b, c] };
      setComparison(next);
    } catch (e) {
      const msg = (e as Error).message;
      if (!/cancelled/i.test(msg)) setError(msg);
    } finally {
      setStage(null);
    }
  }

  const summary = cmp ? compareOutcomes(cmp.current.ASK, cmp.current.FSK) : null;
  const progressPct = runner.progress ? (runner.progress.donePackets / runner.progress.totalPackets) * 100 : 0;

  function exportJson() {
    if (!cmp) return;
    downloadFile(
      `signallab-guided-comparison-${Date.now()}.json`,
      JSON.stringify(
        {
          note: 'Software simulation generated by SignalLab. Not physical RF measurements.',
          generatedAt: new Date().toISOString(),
          sensorReading: reading,
          parameters: params,
          singlePacket: Object.fromEntries(
            Object.entries(results ?? {}).map(([m, r]) => [m, { bitErrors: r!.bitErrors, ber: r!.ber, delivered: r!.delivered, decodeStatus: r!.decode.status }]),
          ),
          experiments: cmp.runs,
          observations: summary?.sentences ?? [],
        },
        null,
        2,
      ),
      'application/json',
    );
  }
  function exportCsv() {
    if (!cmp) return;
    downloadFile(`signallab-guided-comparison-${Date.now()}.csv`, pointsToCsv([cmp.current.ASK, cmp.current.FSK, ...cmp.snrSweep, ...cmp.distanceSweep]), 'text/csv');
  }
  function exportSummary() {
    if (!cmp || !summary) return;
    const p = params;
    const row = (x: ExperimentPoint) =>
      `  ${x.modulation}: BER ${fmtBer(x.ber)} (${x.bitErrors}/${x.bitsCompared}), PDR ${x.pdr.toFixed(1)} %, loss ${x.packetLoss.toFixed(1)} %, processing ${fmtMs(x.avgProcessingMs)}`;
    const text = [
      'SignalLab guided demo summary',
      '=============================',
      `Date: ${new Date().toLocaleString()}`,
      `Packet: sensor S${String(reading.nodeId).padStart(2, '0')}, ${reading.temperatureC} °C, ${reading.humidityPct} %, sequence ${reading.sequence}`,
      `Channel: ${p.distanceM} m, SNR ${p.snrDb} dB at 1 m (receiver Ec/N0 ≈ ${fmtDb(cmp.current.FSK.avgLinkSnrDb)}), ${p.bitRate} bit/s, fading ${p.fading ? 'on' : 'off'}, interference ${p.interference ? 'on' : 'off'}, seed ${p.seed}`,
      '',
      `Results at current settings (${CURRENT_PACKETS} packets each, identical data and noise):`,
      row(cmp.current.ASK),
      row(cmp.current.FSK),
      '',
      'Observations (generated from the measured results):',
      ...summary.sentences.map((s) => `  - ${s}`),
      '',
      'Outcomes depend on receiver design, signal parameters and the simulated channel model.',
      'These are software simulation results, not measurements from radio hardware.',
    ].join('\n');
    downloadFile(`signallab-guided-summary-${Date.now()}.txt`, text, 'text/plain');
  }

  const chartH = presentation ? 280 : 230;

  return (
    <StepFrame
      title="ASK vs FSK: What did we learn?"
      description="One packet is a single coin toss. To compare fairly, simulate many packets for both schemes with identical data and identical noise."
      hint={hint}
      extraActions={
        <SecondaryButton size="lg" icon={<RotateCcw className="h-4 w-4" />} onClick={restart}>
          Run Another Experiment
        </SecondaryButton>
      }
    >
      <div className="space-y-6">
        {/* Single-packet outcome */}
        <div className="flex flex-wrap items-center gap-3 rounded-xl border border-line bg-white px-4 py-3">
          <span className="text-xs font-medium uppercase tracking-wide text-ink-faint">Your packet</span>
          {(['ASK', 'FSK'] as Modulation[]).map((m) => {
            const r = results?.[m];
            if (!r) return null;
            const s = statusOf(r);
            return (
              <StatusBadge key={m} tone={s.tone === 'success' ? 'success' : s.tone === 'error' ? 'error' : 'warning'}>
                {m}: {s.title.replace('Packet ', '').toLowerCase()} · {r.bitErrors} bit error{r.bitErrors === 1 ? '' : 's'}
              </StatusBadge>
            );
          })}
          {other && results && !results[other] && (
            <SecondaryButton onClick={runOther} icon={<Play className="h-4 w-4" />}>
              Run {other} on the same packet
            </SecondaryButton>
          )}
        </div>

        {!cmp ? (
          runner.running ? (
            <div className="rounded-2xl border border-line bg-white p-6">
              <div className="mb-3 flex items-center justify-between gap-3">
                <div className="flex items-center gap-2 text-sm font-medium text-ink">
                  <Loader2 className="h-4 w-4 animate-spin text-accent motion-reduce:animate-none" aria-hidden />
                  Running comparison experiment · {stage}
                </div>
                <SecondaryButton icon={<X className="h-4 w-4" />} onClick={runner.cancel}>
                  Cancel
                </SecondaryButton>
              </div>
              <ProgressBar value={progressPct} label="Comparison progress" />
              {runner.progress && (
                <p className="mt-2 font-mono text-xs text-ink-faint">
                  {runner.progress.current.modulation} · SNR {runner.progress.current.snrDb} dB · {runner.progress.current.distanceM} m · {runner.progress.donePackets}/
                  {runner.progress.totalPackets} packets
                </p>
              )}
            </div>
          ) : (
            <EmptyState
              icon={<BarChart3 className="h-8 w-8" />}
              title="Comparison needs more packets"
              action={
                <PrimaryButton size="lg" icon={<Play className="h-4 w-4" />} onClick={() => void runComparison()}>
                  Run Comparison Experiment
                </PrimaryButton>
              }
            >
              This simulates {CURRENT_PACKETS} packets per scheme at your settings, plus short sweeps over SNR and distance, so the metrics and charts below come from measured
              results. It takes a few seconds.
            </EmptyState>
          )
        ) : (
          <>
            <div>
              <div className="mb-2 flex flex-wrap items-baseline justify-between gap-2">
                <h3 className="text-sm font-semibold text-ink">
                  At your settings · {CURRENT_PACKETS} packets each · receiver SNR ≈ {fmtDb(cmp.current.FSK.avgLinkSnrDb)}
                </h3>
                <SecondaryButton onClick={() => void runComparison()} disabled={runner.running}>
                  Re-run
                </SecondaryButton>
              </div>
              <div className="grid grid-cols-2 gap-3 lg:grid-cols-4">
                {[
                  { label: 'Bit Error Rate', f: (p: ExperimentPoint) => fmtBer(p.ber) },
                  { label: 'Packet Delivery', f: (p: ExperimentPoint) => fmtPct(p.pdr) },
                  { label: 'Packet Loss', f: (p: ExperimentPoint) => fmtPct(p.packetLoss) },
                  { label: 'Processing Time', f: (p: ExperimentPoint) => fmtMs(p.avgProcessingMs) },
                ].map((m) => (
                  <div key={m.label} className="rounded-xl border border-line bg-white p-4">
                    <div className="text-xs font-medium uppercase tracking-wide text-ink-faint">{m.label}</div>
                    <div className="mt-2 space-y-1">
                      {(['ASK', 'FSK'] as Modulation[]).map((mod) => (
                        <div key={mod} className="flex items-baseline justify-between gap-2">
                          <span className={`text-sm font-medium ${mod === 'ASK' ? 'text-ask' : 'text-fsk'}`}>{mod}</span>
                          <span className={`font-mono font-semibold tabular-nums text-ink ${presentation ? 'text-2xl' : 'text-xl'}`}>{m.f(cmp.current[mod])}</span>
                        </div>
                      ))}
                    </div>
                  </div>
                ))}
              </div>
            </div>

            {summary && (
              <Banner tone="info" title="Observation">
                <ul className="list-disc space-y-1 pl-4">
                  {summary.sentences.map((s) => (
                    <li key={s}>{s}</li>
                  ))}
                </ul>
                <p className="mt-2 text-xs">Outcomes depend on receiver design, signal parameters and the simulated channel model. These are simulation results, not hardware measurements.</p>
              </Banner>
            )}

            <div className="grid gap-4 lg:grid-cols-2">
              <div className="rounded-2xl border border-line bg-white p-4">
                <h3 className="mb-1 text-sm font-semibold text-ink">BER versus SNR <span className="font-normal text-ink-faint">· at {params.distanceM} m</span></h3>
                <SweepChart points={cmp.snrSweep} x="snrDb" y="ber" logY height={chartH} />
              </div>
              <div className="rounded-2xl border border-line bg-white p-4">
                <h3 className="mb-1 text-sm font-semibold text-ink">Packet delivery versus distance <span className="font-normal text-ink-faint">· at {params.snrDb} dB</span></h3>
                <SweepChart points={cmp.distanceSweep} x="distanceM" y="pdr" height={chartH} />
              </div>
            </div>

            <div className="flex flex-wrap items-center gap-3 rounded-xl border border-line bg-white px-4 py-3">
              <Download className="h-4 w-4 text-ink-faint" aria-hidden />
              <span className="text-sm font-medium text-ink">Export Results</span>
              <SecondaryButton icon={<FileText className="h-4 w-4" />} onClick={exportCsv}>
                CSV
              </SecondaryButton>
              <SecondaryButton icon={<FileJson className="h-4 w-4" />} onClick={exportJson}>
                JSON
              </SecondaryButton>
              <SecondaryButton icon={<FileText className="h-4 w-4" />} onClick={exportSummary}>
                Summary (.txt)
              </SecondaryButton>
            </div>
          </>
        )}
        {error && (
          <Banner tone="error" title="The comparison could not run">
            {error}
          </Banner>
        )}
      </div>
    </StepFrame>
  );
}
