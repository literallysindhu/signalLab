import { Activity, AudioWaveform, GitCompareArrows } from 'lucide-react';
import { useMemo } from 'react';
import { bytesToBits, encodePacket, fskMarkHz, fskSpaceHz, modulate, waveformConfig } from '../../engine';
import { ModulationCard } from '../../components/ModulationCard';
import { ExpandableSection, cx } from '../../components/ui';
import { fmtHz } from '../../lib/format';
import { useDemo } from './DemoContext';
import { StepFrame } from './StepFrame';
import type { StepProps } from './StepSensor';

const PREVIEW_BITS = 8;

export function StepModulation({ goNext, hint }: StepProps) {
  const { reading, params, selection, setSelection } = useDemo();

  // Preview uses the first byte after the sync byte so it reflects this packet's data.
  const { bits, ask, fsk } = useMemo(() => {
    let b: Uint8Array;
    try {
      // Pick the packet byte with the most 0/1 transitions so both symbols are visible.
      const all = bytesToBits(encodePacket(reading, params.paddingBytes));
      let bestStart = 8;
      let bestScore = -1;
      for (let s = 8; s + PREVIEW_BITS <= all.length - 16; s += 8) {
        let t = 0;
        for (let i = s + 1; i < s + PREVIEW_BITS; i++) if (all[i] !== all[i - 1]) t++;
        if (t > bestScore) {
          bestScore = t;
          bestStart = s;
        }
      }
      b = all.slice(bestStart, bestStart + PREVIEW_BITS);
    } catch {
      b = Uint8Array.from([1, 0, 1, 1, 0, 0, 1, 0]);
    }
    if (!b.some((x) => x) || b.every((x) => x)) b = Uint8Array.from([1, 0, 1, 1, 0, 0, 1, 0]);
    let a = new Float64Array(0);
    let f = new Float64Array(0);
    try {
      a = modulate('ASK', b, waveformConfig(params, 'ASK'));
      f = modulate('FSK', b, waveformConfig(params, 'FSK'));
    } catch {
      /* invalid params are reported on the channel step */
    }
    return { bits: b, ask: a, fsk: f };
  }, [reading, params]);

  const bitStr = Array.from(bits).join('');
  const explanation =
    selection === 'ASK'
      ? `ASK selected. Each 1 is sent as a ${fmtHz(params.carrierHz)} carrier burst and each 0 as silence. The receiver decides by measuring how strong the carrier is.`
      : selection === 'FSK'
        ? `FSK selected. Each 0 is sent at ${fmtHz(fskSpaceHz(params))} and each 1 at ${fmtHz(fskMarkHz(params))}, always at full amplitude. The receiver decides by comparing the two frequencies.`
        : selection === 'BOTH'
          ? 'Compare both selected. The same packet will be sent with ASK and with FSK through identical channel conditions (same noise samples), so the results can be compared fairly.'
          : null;

  return (
    <StepFrame
      title="How should we transmit the data?"
      description="Choose how the bits will be carried by the radio signal. The previews below are generated by the actual modulator from one byte of your packet."
      primaryLabel="Continue to Channel Setup"
      onPrimary={goNext}
      hint={hint}
    >
      <div role="radiogroup" aria-label="Modulation scheme" className="grid gap-5 md:grid-cols-2">
        <ModulationCard
          name="ASK"
          fullName="Amplitude Shift Keying"
          description="Information is represented by changes in signal amplitude."
          icon={<Activity className="h-5 w-5" />}
          preview={ask}
          previewBits={bitStr}
          color="ask"
          selected={selection === 'ASK' || selection === 'BOTH'}
          onSelect={() => setSelection('ASK')}
        />
        <ModulationCard
          name="FSK"
          fullName="Frequency Shift Keying"
          description="Information is represented by changes in signal frequency."
          icon={<AudioWaveform className="h-5 w-5" />}
          preview={fsk}
          previewBits={bitStr}
          color="fsk"
          selected={selection === 'FSK' || selection === 'BOTH'}
          onSelect={() => setSelection('FSK')}
        />
      </div>

      <button
        type="button"
        role="radio"
        aria-checked={selection === 'BOTH'}
        onClick={() => setSelection('BOTH')}
        className={cx(
          'mt-4 flex w-full items-center gap-3 rounded-2xl border-2 bg-white px-5 py-3.5 text-left transition-colors focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-accent',
          selection === 'BOTH' ? 'border-accent' : 'border-dashed border-line hover:border-slate-300',
        )}
      >
        <GitCompareArrows className="h-5 w-5 text-accent" aria-hidden />
        <span className="flex-1">
          <span className="font-medium text-ink">Compare both</span>
          <span className="ml-2 text-sm text-ink-soft">Send the same packet with ASK and FSK under identical conditions</span>
        </span>
        {selection === 'BOTH' && <span className="text-sm font-medium text-accent">Selected</span>}
      </button>

      {explanation && (
        <p className="mt-4 rounded-xl bg-accent-light/50 px-4 py-3 text-[15px] leading-relaxed text-ink" aria-live="polite">
          {explanation}
        </p>
      )}

      <div className="mt-4">
        <ExpandableSection title="Learn how it works">
          <div className="grid gap-5 md:grid-cols-2">
            <div>
              <h4 className="mb-1 font-semibold text-ask">ASK (on-off keying)</h4>
              <p className="font-mono text-[13px] text-ink">s(t) = A(b) · sin(2π f<sub>c</sub> t)</p>
              <p className="mt-1">
                A(1) = A, A(0) = 0. This is on-off keying, the simplest form of ASK. The receiver correlates each bit with the carrier and compares the envelope with a
                threshold. Because the decision depends on amplitude, anything that changes the received amplitude (distance, fading, noise) affects it directly.
              </p>
            </div>
            <div>
              <h4 className="mb-1 font-semibold text-fsk">FSK (binary, continuous phase)</h4>
              <p className="font-mono text-[13px] text-ink">s(t) = A · sin(2π f<sub>b</sub> t + φ)</p>
              <p className="mt-1">
                f<sub>0</sub> = {fmtHz(fskSpaceHz(params))} for 0 and f<sub>1</sub> = {fmtHz(fskMarkHz(params))} for 1; the phase is carried across bit boundaries. The
                receiver measures energy at both frequencies and picks the larger, so it does not need to know the absolute signal level.
              </p>
            </div>
          </div>
        </ExpandableSection>
      </div>
    </StepFrame>
  );
}
