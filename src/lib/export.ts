export function downloadFile(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: `${mime};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function safeFileName(name: string): string {
  return (name || 'experiment').replace(/[^a-z0-9-_]+/gi, '_').replace(/^_+|_+$/g, '').slice(0, 60) || 'experiment';
}

const CSV_COLUMNS: (keyof ExperimentPoint)[] = [
  'modulation', 'snrDb', 'distanceM', 'payloadBytes', 'packetBits', 'packetsSent', 'packetsDelivered', 'pdr', 'pdrStd',
  'packetLoss', 'bitErrors', 'bitsCompared', 'ber', 'berStd', 'checksumFailures', 'undecodable', 'undetectedErrors',
  'avgLinkSnrDb', 'avgMeasuredSnrDb', 'avgProcessingMs', 'airtimeMs', 'energyPerPacket', 'energyPerDelivered',
];

export function pointsToCsv(points: ExperimentPoint[]): string {
  const esc = (v: unknown) => {
    if (v === null || v === undefined) return '';
    const s = typeof v === 'number' ? (Number.isFinite(v) ? String(v) : '') : String(v);
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  };
  const header = ['# Software simulation results (SignalLab). Not real RF measurements.', CSV_COLUMNS.join(',')];
  return [...header, ...points.map((p) => CSV_COLUMNS.map((c) => esc(p[c])).join(','))].join('\n');
}

export function experimentToJson(r: ExperimentResult): string {
  return JSON.stringify(
    {
      note: 'Software simulation generated by SignalLab. These are not physical RF measurements.',
      ...r,
    },
    null,
    2,
  );
}

/** Plain-text summary for reports and demonstrations. Every number comes from the stored result. */
export function experimentSummary(r: ExperimentResult): string {
  const c = r.config;
  const b = c.base;
  const lines: string[] = [];
  lines.push(`SignalLab simulation summary`);
  lines.push(`============================`);
  lines.push(`Experiment: ${c.name}${c.isDemo ? ' (built-in demonstration preset)' : ''}`);
  lines.push(`Run: ${fmtDate(r.startedAt)} (${(r.durationMs / 1000).toFixed(1)} s)`);
  lines.push(`Modulation schemes: ${c.modulations.join(', ')}`);
  lines.push('');
  lines.push('Parameters');
  lines.push(`  SNR values (dB, Ec/N0 at 1 m, reference amplitude): ${c.snrValues.join(', ')}`);
  lines.push(`  Distances (m): ${c.distanceValues.join(', ')}`);
  lines.push(`  Payload sizes (bytes): ${c.paddingValues.map(payloadBytes).join(', ')}`);
  lines.push(`  Packets per point: ${c.packetsPerPoint} × ${c.repetitions} repetition(s) = ${c.packetsPerPoint * c.repetitions}`);
  lines.push(`  Total packets simulated: ${r.totalPackets.toLocaleString()}`);
  lines.push(`  Bit rate: ${b.bitRate} bit/s, samples per bit: ${b.samplesPerBit}, carrier: ${b.carrierHz} Hz, FSK separation: ${b.fskSeparationHz} Hz`);
  lines.push(`  Transmit amplitude: ${b.amplitude}${b.askEqualEnergy ? ' (ASK scaled ×√2 for equal average energy)' : ' (equal peak amplitude)'}`);
  lines.push(`  ASK threshold: ${b.askThreshold} × expected amplitude, path-loss exponent: ${b.pathLossExponent}`);
  lines.push(`  Fading: ${b.fading ? 'Rayleigh block fading' : 'off'}, interference: ${b.interference ? `${b.interferenceDb} dB tone at ${b.interferenceHz} Hz` : 'off'}`);
  lines.push(`  Random seed: ${b.seed}`);
  lines.push('');
  lines.push('Results by modulation (all test points pooled)');
  for (const mod of c.modulations) {
    const pts = r.points.filter((p) => p.modulation === mod);
    const sent = pts.reduce((a, p) => a + p.packetsSent, 0);
    const del = pts.reduce((a, p) => a + p.packetsDelivered, 0);
    const errs = pts.reduce((a, p) => a + p.bitErrors, 0);
    const bits = pts.reduce((a, p) => a + p.bitsCompared, 0);
    lines.push(`  ${mod}: BER ${fmtBer(errs / bits)} (${errs}/${bits} bits), PDR ${((del / sent) * 100).toFixed(1)} % (${del}/${sent} packets)`);
  }
  lines.push('');
  lines.push('Per test point');
  for (const p of r.points) {
    lines.push(
      `  ${p.modulation}  SNR ${p.snrDb} dB  d ${p.distanceM} m  payload ${p.payloadBytes} B  →  BER ${fmtBer(p.ber)}  PDR ${p.pdr.toFixed(1)} %  link Ec/N0 ${p.avgLinkSnrDb.toFixed(1)} dB`,
    );
  }
  const obs = observations(r);
  if (obs.length) {
    lines.push('');
    lines.push('Observations (generated from the measured results above)');
    obs.forEach((o) => lines.push(`  - ${o}`));
  }
  lines.push('');
  lines.push('Note: these results come from a software simulation with a simplified channel model');
  lines.push('(AWGN, log-distance path loss, optional Rayleigh block fading and a tone interferer, ideal timing).');
  lines.push('They are not measurements from physical radio hardware.');
  return lines.join('\n');
}

/** Observations comparing ASK and FSK at matching test points, using only measured data. */
export function observations(r: ExperimentResult): string[] {
  const out: string[] = [];
  const ask = r.points.filter((p) => p.modulation === 'ASK');
  const fsk = r.points.filter((p) => p.modulation === 'FSK');
  if (!ask.length || !fsk.length) return out;
  let askBetter = 0, fskBetter = 0, tie = 0;
  for (const a of ask) {
    const f = fsk.find((x) => x.snrDb === a.snrDb && x.distanceM === a.distanceM && x.payloadBytes === a.payloadBytes);
    if (!f) continue;
    const c = compareOutcomes(a, f).berWinner;
    if (c === 'ASK') askBetter++;
    else if (c === 'FSK') fskBetter++;
    else tie++;
  }
  const n = askBetter + fskBetter + tie;
  if (n) {
    out.push(
      `Across ${n} matched test point(s), FSK had a significantly lower BER at ${fskBetter}, ASK at ${askBetter}, and ${tie} were statistically tied (two-proportion test, ≈95 %).`,
    );
  }
  const askE = ask.reduce((a, p) => a + p.energyPerPacket, 0) / ask.length;
  const fskE = fsk.reduce((a, p) => a + p.energyPerPacket, 0) / fsk.length;
  if (askE > 0 && fskE > 0) out.push(`Mean radiated energy per packet: ASK ${askE.toExponential(2)}, FSK ${fskE.toExponential(2)} (normalised units).`);
  out.push('Outcomes depend on receiver design, signal parameters and the simulated channel model.');
  return out;
}
